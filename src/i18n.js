function interpolate(s, params) {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : `{${k}}`));
}

export const I18nContext = createContext({
  lang: "en",
  t: (key, params) => interpolate(STR.en[key] ?? key, params),
  tx: (_key, fallback) => fallback,
  txRole: (_expert, fallback) => fallback,
});

export function makeT(lang) {
  return (key, params) => interpolate(STR[lang]?.[key] ?? STR.en[key] ?? key, params);
}

export function useI18n() {
  return useContext(I18nContext);
}
